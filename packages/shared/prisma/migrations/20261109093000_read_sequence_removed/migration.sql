-- `service_agreement.read_sequence` goes. Route order lives in
-- `read_route_stop.sequence` (spec 30), on the route, where a walk is.
--
-- WHY
--
-- It was spec 05's answer to route ordering: "an integer that places
-- this agreement in order within its billing cycle's meter reading
-- route. Lower numbers are read first." Nothing read it. Seven sites
-- touched the column and six of them wrote it:
--
--   * the create and PATCH validators, and the two service functions
--     behind them;
--   * the transfer workflow, copying a source agreement's value onto
--     the new one;
--   * the service-agreement import, as a `readSequence` canonical field
--     with the aliases `readsequence`, `readseq`, `routesequence` and
--     `sequence`, a rejection for a non-integer, and a column in the
--     generated template;
--   * the agreement detail page, which rendered it as "Read Sequence"
--     and offered a number input for it in edit mode.
--
-- The seventh was the import's own integration test, asserting back the
-- value it had just written. No `ORDER BY`, no `WHERE`, no index, no
-- constraint, no view: checked in the code and then against the
-- database, which reports no dependent object of any kind on the
-- column. A CSR could type a number into it and no screen, sheet,
-- query or report would ever order anything by it.
--
-- WHY NOT START READING IT INSTEAD
--
-- A single integer on the agreement cannot order a reader's walk.
--
--   * One agreement can serve several premises (multi-premise
--     commercial, master/sub-meter), and a reader walks to buildings,
--     not to contracts — which is why a stop is a premise.
--   * There was no route. The number was "order within its billing
--     cycle's route" while no route entity existed, so every agreement
--     in a cycle shared one unnamed ordering namespace, with nothing
--     stopping two of them claiming 140. A cycle that needs two routes
--     could not be expressed at all.
--   * It belonged to the wrong record. An itinerary changes when a
--     reader's round is rearranged; an agreement changes when service
--     does. `read_route_stop` carries `(utility_id, read_route_id,
--     sequence)` UNIQUE, and `origin` says whether the itinerary is
--     ours to edit or a vendor's to mirror — three facts one nullable
--     column on `service_agreement` had nowhere to put.
--
-- NOTHING IS LOST
--
-- No row carries one. Verified against this stream's dev database
-- before writing this: 0 of 12 agreements have a non-NULL
-- `read_sequence`, and the seed has never written one. A deployment
-- holding values should read them into `read_route` / `read_route_stop`
-- before applying this; there is no automatic migration here because
-- the column does not say which route a number belongs to, and a route
-- is what the new tables are keyed on. Inventing one route per billing
-- cycle would be a guess written into a tenant's data.
--
-- WHAT CHANGES FOR SOMEBODY USING THE SYSTEM
--
-- A file that still carries a read-sequence column now leaves it
-- unmapped and ignored, instead of writing into a field nothing reads.
-- A client still sending `readSequence` to
-- `PATCH /api/v1/service-agreements/:id` gets a 422, because that
-- schema is `.strict()` — the removal is visible rather than silently
-- stripped. And `read_sequence` is no longer a reserved custom-field
-- key on `service_agreement`, so a tenant may now declare a custom
-- field by that name.

ALTER TABLE "service_agreement" DROP COLUMN "read_sequence";

COMMENT ON COLUMN "read_route_stop"."sequence" IS
  'Where this premise falls in the reader''s walk: a sort key, unique per route, assigned in steps of 100 so a stop can be inserted between two others without rewriting the rest. Neither contiguous nor 1-based. The order of a round is the route''s fact, not an agreement''s: service_agreement.read_sequence held an integer of the same name until 2026-11-09, with no reader anywhere.';
